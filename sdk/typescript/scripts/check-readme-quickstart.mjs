/**
 * Extract the README Quick start TypeScript fence and type-check it against
 * the local package sources so the documented sample cannot drift from exports
 * and ProtocolEventEnvelope fields (e.g. eventId vs id).
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, unlinkSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const readmePath = join(root, "README.md");
const snippetPath = join(root, "test", "readme-quickstart.snippet.ts");

const readme = readFileSync(readmePath, "utf8");
const match = readme.match(/## Quick start\r?\n\r?\n```ts\r?\n([\s\S]*?)```/);
if (!match) {
  console.error("README: ## Quick start TypeScript fence not found");
  process.exit(1);
}

let code = match[1];
if (/\bmessage\.event\.id\b/.test(code)) {
  console.error(
    "README Quick start must use message.event.eventId (not message.event.id)",
  );
  process.exit(1);
}
if (!/\bmessage\.event\.eventId\b/.test(code)) {
  console.error("README Quick start must reference message.event.eventId");
  process.exit(1);
}
if (!/\bAgentAccessClient\b/.test(code) || !/\bStaticTokenProvider\b/.test(code)) {
  console.error("README Quick start must use AgentAccessClient and StaticTokenProvider");
  process.exit(1);
}
if (/\bcreateAgentAccessClient\b/.test(code) || /\bcreateStaticTokenProvider\b/.test(code)) {
  console.error("README Quick start must not use removed factory helpers");
  process.exit(1);
}

// Resolve package name to local sources for tsc.
code = code.replace(
  /from\s+["']@actweave\/agent-client["']/,
  'from "../src/index.js"',
);

writeFileSync(snippetPath, `// Generated by scripts/check-readme-quickstart.mjs — do not edit.\n${code}`);

try {
  const result = spawnSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["tsc", "-p", "tsconfig.json", "--noEmit"],
    { cwd: root, stdio: "inherit" },
  );
  if (result.status !== 0) {
    console.error("README Quick start failed type-check");
    process.exit(result.status ?? 1);
  }
  console.log("README Quick start type-check OK");
} finally {
  if (existsSync(snippetPath)) {
    unlinkSync(snippetPath);
  }
}
